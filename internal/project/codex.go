const codexRulesContents = `# Generated by Fledge. Do not edit.

prefix_rule(
    pattern = ["fledge"],
    decision = "allow",
    justification = "Fledge project coordination commands are allowed outside the sandbox.",
    match = [
        "fledge init",
        "fledge agent spawn --name worker --harness codex",
    ],
)

prefix_rule(
    pattern = ["fledge", "start"],
    decision = "forbidden",
    justification = "Run fledge start directly in a user-controlled terminal.",
    match = [
        "fledge start",
        "fledge start --harness codex",
    ],
)

prefix_rule(
    pattern = ["fledge", "stop"],
    decision = "forbidden",
    justification = "Run fledge stop directly in a user-controlled terminal.",
    match = [
        "fledge stop",
        "fledge stop --yes",
    ],
)

prefix_rule(
    pattern = ["herdr", "agent", ["wait", "read", "get", "list", "prompt", "send-keys", "attach", "explain"]],
    decision = "forbidden",
    justification = "Agents must coordinate exclusively through Fledge messaging.",
    match = [
        "herdr agent wait worker",
        "herdr agent read worker",
        "herdr agent get worker",
        "herdr agent list",
        "herdr agent prompt worker status",
        "herdr agent send-keys worker Enter",
        "herdr agent attach worker",
        "herdr agent explain worker",
    ],
)

prefix_rule(
    pattern = ["herdr", "api", "snapshot"],
    decision = "forbidden",
    justification = "Use injected Fledge messages instead of inspecting Herdr session state.",
    match = [
        "herdr api snapshot",
    ],
)

# Herdr accepts global session selectors before its subcommand. Prefix rules
# cannot match the later agent operation across an arbitrary session or remote
# name, so reject these direct forms to prevent bypassing the agent rules above.
prefix_rule(
    pattern = ["herdr", ["--session", "--remote"]],
    decision = "forbidden",
    justification = "Use Fledge commands instead of direct session-scoped Herdr commands.",
    match = [
        "herdr --session project agent wait worker",
        "herdr --remote host agent prompt worker status",
    ],
)
`

